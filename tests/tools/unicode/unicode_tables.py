"""Derives the identifier and normalization tables from the running interpreter's unicodedata and
renders each as a C++ source the repository's clang-format leaves unchanged."""
import unicodedata

LIMIT = 0x110000
INDENT = 8
COLUMN_LIMIT = 185
HANGUL = range(0xAC00, 0xD7A4)
BANNER = ("// Generated by tests/tools/unicode/identifier_tables.py from Python 3.14's unicodedata"
          " (Unicode 16.0.0); regenerate it, never edit it.")


def runs(key, points):
    found = []
    for point in points:
        value = key(point)
        if not value:
            continue
        if found and found[-1][1] == point - 1 and found[-1][2] == value:
            found[-1][1] = point
        else:
            found.append([point, point, value])
    return [tuple(run) for run in found]


def ranges(predicate, points):
    return [(first, last) for first, last, _ in runs(predicate, points)]


def xid_start(point):
    return chr(point).isidentifier()


def xid_continue_only(point):
    return ("a" + chr(point)).isidentifier() and not xid_start(point)


def code(point):
    return "0x{:X}".format(point)


def range_cells(found):
    return ["{{{}, {}}}".format(code(first), code(last)) for first, last in found]


# clang-format lays a long braced list out in columns and, among the column counts that need the
# fewest lines, keeps the smallest; the cells are padded the way it pads them.
def columns(count, width):
    fit = max(1, (COLUMN_LIMIT - INDENT + 1) // (width + 1))
    while fit > 1 and -(-count // (fit - 1)) == -(-count // fit):
        fit -= 1
    return fit


def rows(cells):
    cells = [cell + "," for cell in cells[:-1]] + cells[-1:]
    width = max(len(cell) for cell in cells)
    per_line = columns(len(cells), width)
    lines = []
    for start in range(0, len(cells), per_line):
        line = "".join(cell.ljust(width + 1) for cell in cells[start:start + per_line])
        lines.append(" " * INDENT + line.rstrip())
    return lines


def table(row_type, name, cells):
    lines = rows(cells)
    lines[-1] += "};"
    return ["constexpr {} {}[] = {{".format(row_type, name)] + lines + [""]


def accessor(row_type, name, function):
    return ["std::span<const {}> {}()".format(row_type, function), "{", "    return {};".format(name), "}", ""]


def source(tables):
    lines = [BANNER, "", "#include \"unicode_data.h\"", "", "#include <span>", "", "namespace meios::detail", "{", "",
             "namespace", "{", ""]
    for row_type, name, _, cells in tables:
        lines += table(row_type, name, cells)
    lines += ["}", ""]
    for row_type, name, function, _ in tables:
        lines += accessor(row_type, name, function)
    return "\n".join(lines + ["}", ""])


def identifier_tables():
    outside_ascii = range(0x80, LIMIT)
    return [("code_point_range", "xid_start", "xid_start_ranges", range_cells(ranges(xid_start, outside_ascii))),
            ("code_point_range", "xid_continue", "xid_continue_ranges", range_cells(ranges(xid_continue_only, outside_ascii)))]


def combining_tables():
    found = runs(lambda point: unicodedata.combining(chr(point)), range(LIMIT))
    return [("combining_run", "combining", "combining_runs", ["{{{}, {}, {}}}".format(code(first), code(last), value) for first, last, value in found])]


# A primary composite: its canonical decomposition is exactly the pair, and NFC composes the pair
# back into it, which a composition exclusion does not.
def canonical_pair(point):
    fields = unicodedata.decomposition(chr(point)).split()
    if point in HANGUL or len(fields) != 2 or fields[0].startswith("<"):
        return None
    first, second = (int(field, 16) for field in fields)
    return (first, second, point) if unicodedata.normalize("NFC", chr(first) + chr(second)) == chr(point) else None


def composition_tables():
    found = sorted(row for row in map(canonical_pair, range(LIMIT)) if row)
    return [("composition", "pairs", "compositions", ["{{{}, {}, {}}}".format(*map(code, row)) for row in found])]


# Only a code point that continues an identifier is ever decomposed, and Hangul decomposes
# arithmetically, so the table holds the others alone.
def decomposition_tables():
    entries, pool = [], []
    for point in range(LIMIT):
        form = unicodedata.normalize("NFKD", chr(point)) if point not in HANGUL and ("a" + chr(point)).isidentifier() else chr(point)
        if form != chr(point):
            entries.append("{{{}, {}, {}}}".format(code(point), len(pool), len(form)))
            pool.extend(code(ord(one)) for one in form)
    return [("decomposition", "mappings", "decompositions", entries), ("char32_t", "pool", "decomposition_pool", pool)]


def generated():
    files = [("unicode_identifier_data.cpp", identifier_tables()), ("unicode_combining_data.cpp", combining_tables()),
             ("unicode_composition_data.cpp", composition_tables()), ("unicode_decomposition_data.cpp", decomposition_tables())]
    return [(name, source(tables), [(entry[1], len(entry[3])) for entry in tables]) for name, tables in files]
