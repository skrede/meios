#include "guard_prelude.h"

#include <string_view>

namespace meios::detail
{

std::string_view guard_prelude_source()
{
    return "import ast, math, builtins\n"
           "\n"
           "_ALLOWED = ('abs', 'min', 'max', 'round', 'len', 'str', 'int', 'float', 'bool', 'list',\n"
           "            'dict', 'tuple', 'set', 'sum', 'sorted', 'range', 'enumerate', 'zip', 'any', 'all')\n"
           "_MATH = tuple(n for n in dir(math) if n[0] != '_')\n"
           "_WITHHELD = frozenset(dir(builtins)) - frozenset(_ALLOWED) - frozenset(_MATH)\n"
           "_TRAVERSAL = ('format', 'format_map')\n"
           "_UNITS = (('!radians', 1.0),\n"
           "          ('!degrees', math.pi / 180.0),\n"
           "          ('!meters', 1.0),\n"
           "          ('!millimeters', 0.001),\n"
           "          ('!foot', 0.3048),\n"
           "          ('!inches', 0.0254))\n"
           "\n"
           "def allowed_builtins():\n"
           "    return {n: getattr(builtins, n) for n in _ALLOWED}\n"
           "\n"
           "def math_names():\n"
           "    return {n: getattr(math, n) for n in _MATH}\n"
           "\n"
           "def _named(node):\n"
           "    if isinstance(node, ast.Name):\n"
           "        return node.id\n"
           "    if isinstance(node, ast.Attribute):\n"
           "        return node.attr\n"
           "    if isinstance(node, ast.keyword):\n"
           "        return node.arg or ''\n"
           "    if isinstance(node, ast.arg):\n"
           "        return node.arg\n"
           "    return ''\n"
           "\n"
           "def _offending_dunder(tree):\n"
           "    for node in ast.walk(tree):\n"
           "        name = _named(node)\n"
           "        if name.startswith('__'):\n"
           "            return name\n"
           "    return ''\n"
           "\n"
           "# The formatting mini-language performs attribute access and subscripting on text\n"
           "# written inside a string constant, which the walk never inspects; the traversal is\n"
           "# therefore invisible and the primitive itself is refused instead.\n"
           "def _offending_traversal(tree):\n"
           "    for node in ast.walk(tree):\n"
           "        if isinstance(node, ast.Attribute) and node.attr in _TRAVERSAL:\n"
           "            return node.attr\n"
           "        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load):\n"
           "            if node.id in _TRAVERSAL:\n"
           "                return node.id\n"
           "    return ''\n"
           "\n"
           "def _offending_builtin(tree, bound):\n"
           "    for node in ast.walk(tree):\n"
           "        if isinstance(node, ast.FormattedValue):\n"
           "            # A conversion specifier is a call to a withheld builtin that names no\n"
           "            # identifier the walk could otherwise see; !s is left alone because the\n"
           "            # string type is allowlisted.\n"
           "            if node.conversion == ord('r'):\n"
           "                return 'repr'\n"
           "            if node.conversion == ord('a'):\n"
           "                return 'ascii'\n"
           "        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load):\n"
           "            if node.id in _WITHHELD and node.id not in bound:\n"
           "                return node.id\n"
           "    return ''\n"
           "\n"
           "# ast.walk descends into a lambda or comprehension body, where the reference\n"
           "# implementation's co_names check cannot reach: those bodies are nested code\n"
           "# objects whose names never appear in the top-level co_names tuple.\n"
           "def check_expression(expr, bound):\n"
           "    try:\n"
           "        tree = ast.parse(expr, mode='eval')\n"
           "    except SyntaxError:\n"
           "        return ''\n"
           "    name = _offending_dunder(tree)\n"
           "    if name:\n"
           "        return 'dunder-identifier: ' + name\n"
           "    name = _offending_traversal(tree)\n"
           "    if name:\n"
           "        return 'format-traversal: ' + name\n"
           "    name = _offending_builtin(tree, bound)\n"
           "    if name:\n"
           "        return 'non-allowlisted-builtin: ' + name\n"
           "    return ''\n"
           "\n"
           "def _unit(factor):\n"
           "    def _construct(loader, node):\n"
           "        return factor * float(loader.construct_scalar(node))\n"
           "    return _construct\n"
           "\n"
           "def parse_yaml(text):\n"
           "    import yaml\n"
           "    for tag, factor in _UNITS:\n"
           "        yaml.SafeLoader.add_constructor(tag, _unit(factor))\n"
           "    return yaml.load(text, Loader=yaml.SafeLoader)\n"
           "\n"
           "def read_text(spec):\n"
           "    with open(spec) as stream:\n"
           "        return stream.read()\n";
}

}
